# -*- coding: utf-8 -*-
"""Feder's endnotes (Regensburg 1922, pp. 164-185) as glosses.

Each note in the book is headed by the page of its call, "(S. 19)". The
calls themselves were removed from the text (tools/feder_extract.py), so a
note is placed on the canonical paragraphs printed on that page
(data/feder.json gives each paragraph's pages): page-exact, not
paragraph-exact. The text is the Internet Archive's OCR of the microfilm
(djvu.txt), cleaned with the dictionary pass of tools/feder_fix.py.

Usage: python -P tools/feder_notes.py <MN5044ucmf_5_djvu.txt> data/feder.json data/feder_notes.json
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from feder_fix import fix_word, WORD, z   # noqa: E402

HEAD = re.compile(r'^.*Anmerk\w*\s*zu\s*[,.]?\s*[Sb.].*$', re.M)   # running heads "166 Anmerkungen zu S. 18— 30", OCR'd
# OCR of the page heads: "(S. 19)", "(S.llÖ)", "(3. 161)", "o^S.128)"
START = re.compile(r'(?:^|\n)[^\n(]{0,6}\(?\s*[S35$]\s*[.,^]?\s*([\dlIÖOoi]{2,3})\s*\)\s*\.?')
DIGIT = str.maketrans('lIiÖOo', '111000')
# the microfilm OCR reads "ch" as "di"/"dh" throughout; whole-word forms that are also valid elsewhere
NOTE_FIX = {'audi': 'auch', 'nodi': 'noch', 'dodi': 'doch', 'sidi': 'sich', 'midi': 'mich', 'didi': 'dich',
            'idi': 'ich', 'Sadie': 'Sache', 'nadi': 'nach', 'Nadi': 'Nach', 'Audi': 'Auch', 'dies': 'dies'}

def fix_note_word(w):
    if w in NOTE_FIX:
        return NOTE_FIX[w]
    r = fix_word(w)
    if r:
        return r
    if z(w) == 0:
        c = re.sub(r'd[ih]', 'ch', w)
        if c != w and z(c) > 2.0:
            return c
        # German never has these clusters; the OCR makes them of ch/ck
        c = re.sub(r'sdi', 'sch', w)
        c = re.sub(r'lidi', 'lich', c)
        c = re.sub(r'(?<=[aeiouäöü])dit', 'cht', c)
        c = re.sub(r'(?<=[aeiouäöü])dc', 'ck', c)
        c = re.sub(r'(?<=[a-zäöü])dh(?=[a-zäöü])', 'ch', c)
        if c != w:
            return c
    return None

def clean(t):
    t = re.sub(r'-\s*\n\s*([a-zäöüß])', r'\1', t)          # hyphenated line breaks
    t = re.sub(r'\s+', ' ', t).strip()
    t = WORD.sub(lambda m: fix_note_word(m.group(0)) or m.group(0), t)
    t = re.sub(r'\s+([,.;:])', r'\1', t)
    return t

def main(src, feder, out):
    raw = open(src, encoding='utf-8').read()
    i = raw.find('Vorbemerkungen (S. 18')
    j = raw.find('Li t e r a t u r.', i)   # Feder's reading list follows the last note
    body = HEAD.sub('', raw[i:j])
    body = re.sub(r'^\s*(Vorbemerkungen|Erste Woche|Zweite Woche|Dritte Woche|Vierte Woche|Die Geheimnisse[^\n]*|'
                  r'Regeln[^\n]*|Drei Gebetsweisen|Bemerkungen[^\n]*)\s*\(S\.[^\n]*\)\.?\s*$', '', body, flags=re.M)
    # a cross-reference at a line start, "Figur (S. 171) dürfte", is no note head, nor is
    # a misread page ("60" for 50): the heads run through pages 18-163 without going
    # back, so keep the longest non-decreasing run of candidates
    cand = [m for m in START.finditer(body) if int(m.group(1).translate(DIGIT)) <= 163]
    pg = [int(m.group(1).translate(DIGIT)) for m in cand]
    best, prev = [1] * len(pg), [-1] * len(pg)
    for b in range(len(pg)):
        for a in range(b):
            if pg[a] <= pg[b] and best[a] + 1 > best[b]:
                best[b], prev[b] = best[a] + 1, a
    k = max(range(len(pg)), key=best.__getitem__) if pg else -1
    keep = []
    while k != -1:
        keep.append(k); k = prev[k]
    marks = [cand[k] for k in reversed(keep)]
    print(len(cand) - len(marks), 'candidate heads dropped:', [pg[k] for k in range(len(pg)) if k not in keep])
    F = json.load(open(feder, encoding='utf-8'))
    by_page = {}
    for u in F['units']:
        for p in u['pages']:
            by_page.setdefault(p, []).append(u['n'])
    glosses, skipped = [], 0
    for k, m in enumerate(marks):
        page = int(m.group(1).translate(DIGIT))
        text = clean(body[m.end(): marks[k + 1].start() if k + 1 < len(marks) else len(body)])
        ns = by_page.get(page)
        if not ns or len(text) < 15:
            skipped += 1
            continue
        glosses.append({'page': page, 'spex': [min(ns), max(ns)], 'paras': [text]})
    json.dump({'_note': "Generated by tools/feder_notes.py. Feder's endnotes (pp. 164-185), each placed on the paragraphs "
                        'printed on the page that carries its call.',
               'hinweis': 'Feder 1922, Anmerkungen, pp. 164-185. Uncorrected OCR of the Internet Archive microfilm scan, '
                          'with the dictionary pass of the German layer; misreadings remain.',
               'entries': glosses}, open(out, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(len(glosses), 'notes;', skipped, 'skipped (page outside the text or empty)')

if __name__ == '__main__':
    main(*sys.argv[1:4])
